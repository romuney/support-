"""Общая механика листа: деление на ячейки, вырезание фона, приведение к 128.

Вынесено в модуль, а не скопировано в оба скрипта: нарезка стикеров и сборка
GIF читают один и тот же лист от Nano Banana, и вторая копия разъехалась бы
молча — статика и анимация начали бы отличаться размером персонажа.
"""

from PIL import Image, ImageChops, ImageDraw, ImageFilter

# Допуск по ЯРКОСТИ вокруг цвета фона, в единицах канала L. Держать широким
# можно и нужно: фон у Nano Banana не идеально ровный, а от персонажа маску
# защищает не яркость, а насыщенность — см. `key_background`.
FLOOD_THRESH = 45
# Предел локального размаха яркости в окне 3×3, при котором пиксель ещё
# считается ровным фоном. Замер по листу пака: фон 1–2 (99-й процентиль 15
# на блоках JPEG), внутренность серой кепки — медиана 10. 8 проходит между.
EDGE_MAX = 8
# Предел насыщенности (max(R,G,B) - min(R,G,B)), при котором пиксель ещё
# считается фоном. Замер по листу пака: фон 0–6, кремовая шерсть в тени
# 3–72 при медиане 40. 12 проходит между ними с запасом в обе стороны.
SAT_MAX = 12


def split_grid(img, cols, rows):
    """Деление листа на ячейки — по разделителям, если они есть.

    Ровного деления НЕ хватает, и это выяснилось на листе пака: промпт
    просил промежутки того же серого, что и фон, а модель нарисовала между
    ячейками БЕЛЫЕ полосы шириной ~20 px и разной толщины, из-за чего ячейки
    вышли по 1003–1014 px вместо ровных 1024. Ровное деление вносит в каждую
    ячейку кусок чужой полосы, а дальше молча ломается вырезание фона:
    заливка идёт от края и сравнивается с ПРЕОБЛАДАЮЩИМ цветом рамки, до
    белого от серого 381 при пороге 60 — полоса остаётся белой каймой
    по краю прозрачного PNG, и видно это уже в Mattermost на тёмной теме.

    Поэтому сначала ищем разделители, и только если их нет — делим ровно.
    """
    cuts_x = find_gaps(img, cols, axis=0)
    cuts_y = find_gaps(img, rows, axis=1)
    out = []
    for r in range(rows):
        for c in range(cols):
            out.append(img.crop((cuts_x[c][0], cuts_y[r][0],
                                 cuts_x[c][1], cuts_y[r][1])))
    return out


def find_gaps(img, n, axis, bright=200, share=0.7, inset=2):
    """Границы n ячеек вдоль оси: по светлым полосам, иначе ровно.

    Полосой считается линия, где почти всё (share) ярче `bright` по всем
    каналам: фон листа — средний серый, персонаж кремовый с тёмными глазами,
    и ни то, ни другое сплошной светлой линией через весь лист не идёт.

    Полос должно найтись ровно n-1. Меньше — модель нарисовала не все
    (или не рисовала вовсе), больше — в лист попало что-то ещё светлое;
    в обоих случаях доверять находке нельзя, и деление идёт ровным. Тихо
    подстроиться под «почти подошло» здесь хуже, чем поделить ровно:
    сдвиг на одну ячейку переименует весь пак.

    `inset` срезает сглаженный край полосы: у JPEG он размыт на пару
    пикселей, и без запаса светлая кайма остаётся в ячейке.
    """
    size = img.size[axis]
    px = img.convert("RGB").load()
    other = img.size[1 - axis]
    # Шаг по второй оси: сплошную полосу видно и по каждому десятому пикселю,
    # а полный проход по 4096×4096 стоит секунды на ровном месте.
    step = max(1, other // 200)

    bands, start = [], None
    for i in range(size):
        lit = 0
        total = 0
        for j in range(0, other, step):
            xy = (i, j) if axis == 0 else (j, i)
            c = px[xy]
            total += 1
            if c[0] > bright and c[1] > bright and c[2] > bright:
                lit += 1
        if lit / total >= share:
            if start is None:
                start = i
        elif start is not None:
            bands.append((start, i - 1))
            start = None
    if start is not None:
        bands.append((start, size - 1))

    # Полосы по краям листа — это поля, а не разделители.
    bands = [b for b in bands if b[0] > 0 and b[1] < size - 1]

    if len(bands) != n - 1:
        return [(round(k * size / n), round((k + 1) * size / n))
                for k in range(n)]

    starts = [0] + [b[1] + 1 + inset for b in bands]
    stops = [b[0] - inset for b in bands] + [size]
    return list(zip(starts, stops))


def key_background(cell, thresh=FLOOD_THRESH, sat_max=SAT_MAX,
                   edge_max=EDGE_MAX):
    """Убрать фон: пиксель серый по цвету И связан с краем ячейки.

    Два условия, и ни одного из них по отдельности не хватает.

    ТОЛЬКО СВЯЗНОСТЬ (заливка от края с допуском по цвету) — так было
    сделано сперва, и на листе пака это провалилось в обе стороны сразу.
    Допуск 60 выел собаке грудь: тень на кремовой шерсти отличается от
    фона на 51 из 381, то есть меньше порога, и заливка ушла внутрь
    персонажа через границу подбородка. Допуск 20 грудь сохранил, но
    оставил серые лоскуты в вогнутых местах — у лапы, под флажком, сбоку
    от замка: PIL сравнивает каждый пиксель с ЗАТРАВОЧНЫМ, а фон
    у Nano Banana не идеально ровный, и до дальних углов допуск не дотянул.
    Между «съело персонажа» и «оставило грязь» промежутка не нашлось.

    ТОЛЬКО ЦВЕТ (снять всё серое по всей ячейке) — так нельзя тем более:
    клавиатура в анимации серая и почти нейтральная (яркость 124–195,
    насыщенность 8–22 при фоне 118 и 0), то есть тёмной своей частью она
    попадает в маску, и глобальное сравнение проело бы её насквозь.
    Спасает её именно связность: снаружи клавиатура окружена светлым
    краем, и заливка от края внутрь не проходит.

    Замер по ячейке `bully_high` показал, чем эти два множества расходятся
    на самом деле:

        фон              яркость 118–124   насыщенность 0–6
        съеденная грудь  яркость 103–162   насыщенность 3–72 (медиана 40)

    Фон — не просто «примерно того же тона», он НЕЙТРАЛЬНЫЙ: у него нет
    цвета вовсе. Шерсть кремовая и в тени, то есть цветная. Поэтому здесь
    сначала строится маска «нейтральный серый нужной яркости» (`sat_max`
    по насыщенности, `thresh` по яркости), и уже по ней идёт заливка
    от краёв. Допуск по яркости можно держать широким: от персонажа маску
    защищает не он, а насыщенность.

    ТРЕТЬЕ УСЛОВИЕ — ГРАДИЕНТ, и без него первые два дали видимый брак.
    Серая кепка `bully_unknown` нейтральна не хуже фона (насыщенность 6),
    и по цвету от него неотличима вовсе: её тень — яркость 90–140 при фоне
    118. Заливка входила в кепку по шву и оставляла в ней прозрачные
    трещины; то же самое на ухе у `bully_fail`. В интерфейсе это видно
    как белые чёрточки на светлой теме и чёрные на тёмной — то есть как
    неаккуратное вырезание, хотя вырезано ровно по цвету.

    Отличается фон не цветом, а РОВНОСТЬЮ: локальный размах яркости в окне
    3×3 у фона 1–2 (99-й процентиль 15 на блоках JPEG), внутри кепки
    медиана 10 при 99-м процентиле 100. Пиксели с размахом больше `edge_max`
    в маску не попадают, и заливка об них останавливается: сквозь границу
    силуэта и сквозь шов на кепке она больше не проходит. Мягкие,
    размытые края это не ломает — у них размах низкий, и фон снимается
    вплотную, как раньше.

    Расплата за третье условие — крапины: одинокие непрозрачные точки
    на месте блоков JPEG в фоне и такие же дырки в персонаже. Их снимает
    морфология в конце: закрытие затягивает дырки до 2 px, открытие
    убирает островки до 2 px. Силуэт от этого не страдает — он на три
    порядка крупнее.

    Сеятели берутся по ВСЕМУ периметру. Фиксированный набор точек ломается,
    как только персонаж доходит до края кадра: сеятель попадает в лапу.
    Здесь этого мало — сеятель просто не попадёт в маску, — но перебор
    периметра стоит копейки и оставлен как есть.
    """
    rgb = cell.convert("RGB")
    w, h = rgb.size

    # Преобладающий цвет рамки. Огрубление до 8 уровней на канал гасит шум
    # и лёгкую фактуру, из-за которой точное сравнение дало бы столько же
    # «цветов фона», сколько пикселей.
    px = rgb.load()
    border = [(x, 0) for x in range(w)] + [(x, h - 1) for x in range(w)] \
        + [(0, y) for y in range(h)] + [(w - 1, y) for y in range(h)]
    tally = {}
    for xy in border:
        c = px[xy]
        k = (c[0] // 8, c[1] // 8, c[2] // 8)
        tally[k] = tally.get(k, 0) + 1
    dom = max(tally, key=tally.get)
    dom = (dom[0] * 8 + 4, dom[1] * 8 + 4, dom[2] * 8 + 4)

    if max(dom) - min(dom) > sat_max:
        # Цветной фон рушит главное допущение, и молча снять при этом
        # нечего: маска окажется пустой, ячейка уедет в Mattermost
        # с квадратом фона. Лучше остановиться и сказать, что не так.
        raise ValueError(
            f"фон ячейки не нейтральный (RGB {dom}) — эта нарезка рассчитана "
            "на плоский серый фон из промпта")

    # Насыщенность как max(R,G,B) - min(R,G,B): канальные операции PIL идут
    # в C, а поштучный обход миллиона пикселей на ячейку стоил бы секунды.
    r, g, b = rgb.split()
    mx = ImageChops.lighter(ImageChops.lighter(r, g), b)
    mn = ImageChops.darker(ImageChops.darker(r, g), b)
    sat = ImageChops.subtract(mx, mn)
    lum = rgb.convert("L")
    dom_lum = round(0.299 * dom[0] + 0.587 * dom[1] + 0.114 * dom[2])

    # Локальный размах яркости = морфологический градиент: max по окну 3×3
    # минус min по нему же. Дешевле свёрток и не зависит от направления края.
    grad = ImageChops.subtract(lum.filter(ImageFilter.MaxFilter(3)),
                               lum.filter(ImageFilter.MinFilter(3)))

    neutral = sat.point(lambda v: 255 if v <= sat_max else 0)
    inband = lum.point(lambda v: 255 if abs(v - dom_lum) <= thresh else 0)
    flat = grad.point(lambda v: 255 if v <= edge_max else 0)
    mask = ImageChops.multiply(ImageChops.multiply(neutral, inband), flat)

    # Заливка идёт по МАСКЕ, а не по картинке: внутри маски все пиксели
    # ровно 255, поэтому thresh=0 — заливка не может протечь никуда, кроме
    # соседнего пикселя, который тоже признан фоном.
    mp = mask.load()
    for xy in border:
        if mp[xy] == 255:
            ImageDraw.floodfill(mask, xy, 128, thresh=0)

    alpha = mask.point(lambda v: 0 if v == 128 else 255)
    # Закрытие (расширить непрозрачное, потом сжать) затягивает крапчатые
    # дырки; открытие (сжать, потом расширить) убирает такие же островки
    # фона. Порядок именно такой: сперва вернуть персонажу его пиксели,
    # потом чистить фон, иначе открытие разъело бы дырки ещё шире.
    alpha = alpha.filter(ImageFilter.MaxFilter(3)).filter(ImageFilter.MinFilter(3))
    alpha = alpha.filter(ImageFilter.MinFilter(3)).filter(ImageFilter.MaxFilter(3))

    out = cell.convert("RGBA")
    out.putalpha(alpha)
    return out


def content_box(cell):
    """Границы непрозрачного содержимого. None — ячейка пустая."""
    return cell.getbbox()


def fit_square(cell, box, size=128, pad=0.02):
    """Обрезать по box, дополнить до квадрата и привести к size.

    `box` приходит СНАРУЖИ намеренно: у анимации он обязан быть общим на все
    кадры, иначе каждый кадр обрежется по своему силуэту, персонаж поедет
    от кадра к кадру, и цикл будет дёргаться при неподвижной камере.
    """
    crop = cell.crop(box)
    w, h = crop.size
    side = max(w, h)
    side = int(round(side * (1 + 2 * pad))) or 1
    canvas = Image.new("RGBA", (side, side), (0, 0, 0, 0))
    canvas.paste(crop, ((side - w) // 2, (side - h) // 2))
    return canvas.resize((size, size), Image.LANCZOS)


def union_box(boxes):
    """Объединение границ — общая рамка для всех кадров анимации."""
    boxes = [b for b in boxes if b]
    if not boxes:
        return None
    return (min(b[0] for b in boxes), min(b[1] for b in boxes),
            max(b[2] for b in boxes), max(b[3] for b in boxes))

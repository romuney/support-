def node(name, ntype, version, pos, params, **extra):
    n = {
        "parameters": params,
        "type": ntype,
        "typeVersion": version,
        "position": pos,
        "id": name.lower().replace(" ", "-").replace("_", "-"),
        "name": name,
    }
    n.update(extra)
    return n


def wf(name, nodes, connections):
    return {
        "name": name,
        "nodes": nodes,
        "connections": connections,
        "active": False,
        "settings": {"executionOrder": "v1"},
        "pinData": {},
    }


def chain(*names):
    """Линейная связка main-выходов по порядку."""
    out = {}
    for a, b in zip(names, names[1:]):
        out[a] = {"main": [[{"node": b, "type": "main", "index": 0}]]}
    return out



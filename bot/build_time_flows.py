def read_prompt(path):
    """Читает промпт из prompts/*.md, срезая HTML-комментарии для разработчика.

    Комментарии в начале файла объясняют, почему промпт устроен так, а не иначе,
    и адресованы человеку, который его правит. Модели они не нужны, а платить
    за них токенами пришлось бы в каждом вызове — ровно та же ошибка, из-за
    которой раньше в промпт уезжали 1151 символ комментариев из index.md.
    """
    text = open(path, encoding="utf-8").read()
    out = re.sub(r"<!--.*?-->\n*", "", text, flags=re.S)
    assert "{{QUESTION}}" in out, f"в {path} нет плейсхолдера {{{{QUESTION}}}}"
    return out.strip()


def read_mode_rules(path):
    """Читает промпт режима: те же срезанные комментарии, но без {{QUESTION}}.

    Правила режима вклеиваются не в промпт напрямую, а в Code-ноду «Build
    materials» — она и решает, включать их или нет. Поэтому плейсхолдеров
    вопроса и материалов здесь нет: текст едет к модели целиком либо не едет
    вовсе.
    """
    text = open(path, encoding="utf-8").read()
    return re.sub(r"<!--.*?-->\n*", "", text, flags=re.S).strip()



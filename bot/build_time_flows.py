# Фильтр триггера лички задаётся в UI и пиннится сюда файлом.
#
# У фильтра Channels есть операция «Is Direct Message» — она и нужна: ловит все
# личные диалоги с ботом, не перечисляя людей. Точный ключ этой операции в JSON
# неизвестен: в Time examples.json есть только channels с nameAuto, внутренней
# документации по ноде нет. Угадать имя поля — значит получить фильтр, который
# не сработает молча.
#
# Поэтому фильтр настраивается в n8n один раз руками (Add Filter → Channels →
# Operation: Is Direct Message), нода копируется Ctrl+C в файл
# dm_trigger_filter.json, и сборщик подставляет её postedFilters дословно.
# Файла нет — в собранном адаптере остаётся пустой фильтр, и n8n при активации
# честно падает с «All filters are empty», вместо тихо неработающей лички.
DM_FILTER_FILE = "dm_trigger_filter.json"


def load_dm_filter():
    """Возвращает postedFilters из скопированной из n8n ноды, либо None."""
    if not os.path.exists(DM_FILTER_FILE):
        return None
    raw = json.load(open(DM_FILTER_FILE, encoding="utf-8"))
    # Ctrl+C в n8n даёт {"nodes": [...], "connections": {...}}, но допускаем
    # и просто ноду, и сразу объект postedFilters.
    if "nodes" in raw:
        raw = next(
            n for n in raw["nodes"] if n.get("type", "").endswith("mattermostTrigger")
        )
    params = raw.get("parameters", raw)
    return params.get("postedFilters", params)


